using Microsoft.EntityFrameworkCore;
using prohpharmacy_trekking_app.Database;
using prohpharmacy_trekking_app.Features.Ledger.Entities;
using prohpharmacy_trekking_app.Features.Ledger.Enums;
using prohpharmacy_trekking_app.Features.Trekking.Entities;
using prohpharmacy_trekking_app.Features.Trekking.Enums;

namespace prohpharmacy_trekking_app.Services.Invoicing;

public sealed class InvoiceLedgerService(AppDbContext db)
{
    public async Task SynchronizeAsync(SaleInvoice invoice, CancellationToken ct)
    {
        var debit = db.CustomerLedgerEntries.Local.FirstOrDefault(e => e.SaleInvoiceId == invoice.Id && e.InvoicePaymentId == null)
            ?? await db.CustomerLedgerEntries.SingleOrDefaultAsync(e => e.SaleInvoiceId == invoice.Id && e.InvoicePaymentId == null, ct);
        if (invoice.Status == SaleInvoiceStatus.Voided || invoice.TotalAmount == 0)
        {
            if (debit is not null) db.CustomerLedgerEntries.Remove(debit);
        }
        else
        {
            if (debit is null)
            {
                debit = Entry(invoice);
                debit.EntryType = LedgerEntryType.Debit;
                debit.RecordedAt = invoice.IssuedAt;
                db.CustomerLedgerEntries.Add(debit);
            }
            debit.CustomerAccountId = invoice.CustomerAccountId;
            debit.Amount = invoice.TotalAmount;
            debit.Description = $"Invoice {invoice.InvoiceNumber}";
        }

        foreach (var payment in invoice.Payments.Where(p => db.Entry(p).State == EntityState.Added))
        {
            var credit = Entry(invoice);
            credit.InvoicePaymentId = payment.Id;
            credit.EntryType = LedgerEntryType.Credit;
            credit.Amount = payment.Amount;
            credit.PaymentMethod = payment.PaymentMethod?.ToString();
            credit.RecordedAt = payment.RecordedAt;
            credit.CreatedByStaffId = payment.RecordedByStaffId;
            credit.Description = $"Payment {payment.ReceiptNumber} — Invoice {invoice.InvoiceNumber}";
            db.CustomerLedgerEntries.Add(credit);
        }
    }

    private static CustomerLedgerEntry Entry(SaleInvoice invoice) => new()
    {
        SaleInvoiceId = invoice.Id,
        CustomerAccountId = invoice.CustomerAccountId,
        TrekkingTripId = invoice.TrekkingTripId,
        TrekkingTripStopId = invoice.TrekkingTripStopId,
        IsAutoGenerated = true,
        CreatedByStaffId = invoice.Stop.TrekkingTrip.SalesStaffId ?? invoice.Stop.TrekkingTrip.DriverStaffId,
        CreatedAt = DateTime.UtcNow
    };
}
